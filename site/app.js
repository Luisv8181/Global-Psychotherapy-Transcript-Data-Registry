  // ---------- tooltips ----------
  const tip = $('#tip');
  const showTip = (el, x, y) => { tip.textContent = el.dataset.tip; tip.classList.add('show'); const w = tip.offsetWidth; tip.style.left = Math.min(innerWidth - w - 8, Math.max(8, x - w / 2)) + 'px'; tip.style.top = (y - 40) + 'px'; };
  document.addEventListener('mousemove', e => { const el = e.target.closest('[data-tip]'); el ? showTip(el, e.clientX, e.clientY) : tip.classList.remove('show'); });
  document.addEventListener('focusin', e => { const el = e.target.closest('[data-tip]'); if (el) { const r = el.getBoundingClientRect(); showTip(el, r.left + r.width / 2, r.top); } });
  document.addEventListener('focusout', () => tip.classList.remove('show'));

  // ---------- router ----------
  let current = '';
  function route() {
    const h = location.hash || '#/';
    if (/^#[\w-]+$/.test(h) && byId[h.slice(1)]) { location.replace('#/dataset/' + h.slice(1)); return; }
    const [pageName, arg] = h.replace(/^#\/?/, '').split('/').map(s => decodeURIComponent(s || ''));
    const name = pageName || 'cover';
    // Swap in a fresh <main> so listeners from the previous page do not accumulate.
    const fresh = view.cloneNode(false); view.replaceWith(fresh); view = fresh;
    const titles = { cover: 'The Registry', index: 'Index · The Registry', atlas: 'Atlas · The Registry', videos: 'Video catalog · The Registry', standards: 'Editorial standards · The Registry' };
    document.title = titles[name] || 'The Registry';
    ({ index: () => index(arg), dataset: () => dossier(arg), atlas, videos: videoPage, standards }[name] || cover)();
    document.querySelectorAll('[data-nav]').forEach(a => a.setAttribute('aria-current', a.dataset.nav === (name === 'dataset' ? 'index' : name) ? 'page' : 'false'));
    const key = name + '/' + (arg || '');
    if (key !== current) { window.scrollTo(0, 0); view.focus({ preventScroll: true }); }
    current = key;
    tip.classList.remove('show');
  }
  window.addEventListener('hashchange', route);
  route();
